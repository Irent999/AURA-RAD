export function bqToCi(bq: number): number {
  return bq / CURIE_TO_BQ;
}

export function ciToBq(ci: number): number {
  return ci * CURIE_TO_BQ;
}

export function tbqToBq(tbq: number): number {
  return tbq * 1e12;
}

export function bqToTbq(bq: number): number {
  return bq / 1e12;
}

export function getExtendedIsotope(symbol: string): Isotope3D {
  const found = EXTENDED_ISOTOPE_LIBRARY.find(
    (iso) => iso.symbol.toLowerCase() === symbol.toLowerCase(),
  );
  if (found) return found;
  return EXTENDED_ISOTOPE_LIBRARY[1]!;
}

export function filterIsotopesByCategory(category: NuclideCategory | "all"): Isotope3D[] {
  if (category === "all") return EXTENDED_ISOTOPE_LIBRARY;
  return EXTENDED_ISOTOPE_LIBRARY.filter((iso) => iso.category === category);
}

export function searchExtendedIsotopes(query: string): Isotope3D[] {
  const q = query.trim().toLowerCase();
  if (!q) return EXTENDED_ISOTOPE_LIBRARY;
  return EXTENDED_ISOTOPE_LIBRARY.filter(
    (iso) =>
      iso.symbol.toLowerCase().includes(q) ||
      iso.name.toLowerCase().includes(q) ||
      iso.nameRu.toLowerCase().includes(q) ||
      iso.description.toLowerCase().includes(q),
  );
}
