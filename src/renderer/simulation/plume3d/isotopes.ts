export function getExtendedIsotope(symbol: string): Isotope3D {
  const found = EXTENDED_ISOTOPE_LIBRARY.find(
    (iso) => iso.symbol.toLowerCase() === symbol.toLowerCase(),
  );
  if (found) return found;
  // Default to Cs-137 if not found
  return EXTENDED_ISOTOPE_LIBRARY[1]!;
}

export function searchExtendedIsotopes(query: string): Isotope3D[] {
  const q = query.trim().toLowerCase();
  if (!q) return EXTENDED_ISOTOPE_LIBRARY;
  return EXTENDED_ISOTOPE_LIBRARY.filter(
    (iso) =>
      iso.symbol.toLowerCase().includes(q) ||
      iso.name.toLowerCase().includes(q) ||
      iso.nameRu.toLowerCase().includes(q) ||
      iso.description.toLowerCase().includes(q),
  );
}
