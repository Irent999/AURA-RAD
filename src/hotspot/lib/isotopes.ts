export function getIsotope(symbol: string): Isotope | undefined {
  return ISOTOPE_LIBRARY.find((iso) => iso.symbol === symbol);
}

export function decayActivity(
  initialActivity: number,
  decayConstant: number,
  timeSeconds: number,
): number {
  return initialActivity * Math.exp(-decayConstant * timeSeconds);
}

